import { z } from "zod";
import { IdSchema, MessageTextSchema, TimestampSchema } from "../common";
import { MessageRoleSchema } from "../enums";
import { JobSummarySchema } from "./jobs";

export const CONVERSATION_TITLE_MAX_LENGTH = 200;

export const ConversationSchema = z.object({
  id: IdSchema,
  projectId: IdSchema,
  title: z.string().nullable(),
  /** Studio agent that holds this conversation's producer session, once one has replied. */
  deviceId: IdSchema.nullable(),
  /**
   * The content item this conversation is about (`content.conversation`); null for project
   * conversations. Optional until every server sends it.
   */
  contentItemId: IdSchema.nullable().optional(),
  createdBy: IdSchema,
  createdAt: TimestampSchema,
  lastMessageAt: TimestampSchema.nullable(),
});
export type Conversation = z.infer<typeof ConversationSchema>;

export const CreateConversationSchema = z.object({
  title: z.string().trim().min(1).max(CONVERSATION_TITLE_MAX_LENGTH).optional(),
});
export type CreateConversation = z.infer<typeof CreateConversationSchema>;

/** A structured part of a message, such as a tool call summary. The text stays in `text`. */
export const MessageBlockSchema = z.looseObject({
  type: z.string().min(1),
});
export type MessageBlock = z.infer<typeof MessageBlockSchema>;

/** Stored in `messages.content`. */
export const MessageContentSchema = z.object({
  text: z.string(),
  blocks: z.array(MessageBlockSchema).optional(),
});
export type MessageContent = z.infer<typeof MessageContentSchema>;

export const MessageSchema = z.object({
  id: IdSchema,
  conversationId: IdSchema,
  role: MessageRoleSchema,
  authorUserId: IdSchema.nullable(),
  jobId: IdSchema.nullable(),
  clientMessageId: IdSchema.nullable(),
  content: MessageContentSchema,
  createdAt: TimestampSchema,
});
export type Message = z.infer<typeof MessageSchema>;

/**
 * `clientMessageId` is generated by the client. Posting the same id twice returns the stored
 * message instead of creating a second one.
 */
export const PostMessageRequestSchema = z.object({
  text: MessageTextSchema,
  clientMessageId: IdSchema,
});
export type PostMessageRequest = z.infer<typeof PostMessageRequestSchema>;

/** The stored user message and the `producer.chat` job that answers it. */
export const PostMessageResponseSchema = z.object({
  message: MessageSchema,
  job: JobSummarySchema,
});
export type PostMessageResponse = z.infer<typeof PostMessageResponseSchema>;
