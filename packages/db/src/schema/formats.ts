import type { FormatRules } from "@loomcast/contracts";
import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  check,
  foreignKey,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { createdAt, timestamptz, uuidPrimaryKey } from "./columns";
import { seriesStatus } from "./enums";
import { projects } from "./projects";
import { users } from "./users";

/**
 * A format of a project: the rules (length, voice, style, captions, cadence) its series produce
 * with. The rules live in immutable `format_versions`; every change, even a rename, writes a new
 * version and moves `currentVersionId`.
 *
 * A format always has a version, so `currentVersionId` is never null. The foreign key to
 * `format_versions (format_id, id)` also proves that the current version belongs to this format.
 * It is `DEFERRABLE INITIALLY DEFERRED` (written into the migration by hand; drizzle cannot
 * express it), so a format and its first version are inserted in one transaction in either
 * order, with the ids generated by the caller.
 */
export const formats = pgTable(
  "formats",
  {
    id: uuidPrimaryKey(),
    projectId: uuid("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    slug: text("slug").notNull(),
    currentVersionId: uuid("current_version_id").notNull(),
    createdAt: createdAt(),
    updatedAt: timestamptz("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
    archivedAt: timestamptz("archived_at"),
  },
  (t) => [
    uniqueIndex("formats_project_id_slug_uq").on(t.projectId, t.slug),
    // Target of `series_format_fk`, which keeps a series and its format in one project.
    uniqueIndex("formats_project_id_id_uq").on(t.projectId, t.id),
    foreignKey({
      name: "formats_current_version_fk",
      columns: [t.id, t.currentVersionId],
      foreignColumns: [formatVersions.formatId, formatVersions.id],
    }),
  ],
);

/** One immutable version of a format's rules. Versions count up from 1 per format. */
export const formatVersions = pgTable(
  "format_versions",
  {
    id: uuidPrimaryKey(),
    formatId: uuid("format_id")
      .notNull()
      .references((): AnyPgColumn => formats.id, { onDelete: "cascade" }),
    versionNo: integer("version_no").notNull(),
    rules: jsonb("rules").$type<FormatRules>().notNull(),
    createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("format_versions_format_id_version_no_uq").on(t.formatId, t.versionNo),
    // Target of `formats_current_version_fk`.
    uniqueIndex("format_versions_format_id_id_uq").on(t.formatId, t.id),
    check("format_versions_version_no_ck", sql`${t.versionNo} >= 1`),
  ],
);

/**
 * A series of a project. Its items follow the rules of its format, which must belong to the same
 * project (`series_format_fk`). A format in use by a series cannot be deleted.
 */
export const series = pgTable(
  "series",
  {
    id: uuidPrimaryKey(),
    projectId: uuid("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    slug: text("slug").notNull(),
    formatId: uuid("format_id").notNull(),
    status: seriesStatus("status").notNull().default("active"),
    createdAt: createdAt(),
    updatedAt: timestamptz("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
    archivedAt: timestamptz("archived_at"),
  },
  (t) => [
    uniqueIndex("series_project_id_slug_uq").on(t.projectId, t.slug),
    index("series_format_id_idx").on(t.formatId),
    foreignKey({
      name: "series_format_fk",
      columns: [t.projectId, t.formatId],
      foreignColumns: [formats.projectId, formats.id],
    }),
  ],
);

export type FormatRow = typeof formats.$inferSelect;
export type NewFormatRow = typeof formats.$inferInsert;
export type FormatVersionRow = typeof formatVersions.$inferSelect;
export type NewFormatVersionRow = typeof formatVersions.$inferInsert;
export type SeriesRow = typeof series.$inferSelect;
export type NewSeriesRow = typeof series.$inferInsert;
