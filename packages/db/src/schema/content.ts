import type { ContentItemError, PostMediaEntry, Script, Storyboard } from "@loomcast/contracts";
import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  boolean,
  check,
  foreignKey,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { assets } from "./assets";
import { createdAt, timestamptz, uuidPrimaryKey } from "./columns";
import {
  actorKind,
  contentCreatedVia,
  pipelineState,
  postFormat,
  produceTarget,
  reviewDecision,
  versionCreatedVia,
} from "./enums";
import { formatVersions, series } from "./formats";
import { jobs } from "./jobs";
import { projects } from "./projects";
import { users } from "./users";

/**
 * A content item: one short video on its way from idea to publication. Its artifacts live in
 * immutable `content_versions`; `state` is where the item stands in `PIPELINE_TRANSITIONS`.
 *
 * Every item has a version from creation (version 1 is the bare idea), so `currentVersionId` is
 * never null. The foreign key to `content_versions (item_id, id)` also proves that the current
 * version belongs to this item. It is `DEFERRABLE INITIALLY DEFERRED` (written into the migration
 * by hand; drizzle cannot express it): insert the item and its first version in one transaction,
 * with the ids generated by the caller.
 */
export const contentItems = pgTable(
  "content_items",
  {
    id: uuidPrimaryKey(),
    projectId: uuid("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    seriesId: uuid("series_id").references(() => series.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    pitch: text("pitch"),
    topic: text("topic"),
    state: pipelineState("state").notNull().default("idea"),
    currentVersionId: uuid("current_version_id").notNull(),
    /** When the item should be published. */
    targetAt: timestamptz("target_at"),
    /** Where autopilot stops; null when autopilot is off. */
    autopilotTarget: produceTarget("autopilot_target"),
    /** The last production failure, cleared by the next successful step. */
    lastError: jsonb("last_error").$type<ContentItemError>(),
    createdVia: contentCreatedVia("created_via").notNull(),
    createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
    createdAt: createdAt(),
    updatedAt: timestamptz("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
    archivedAt: timestamptz("archived_at"),
  },
  (t) => [
    // Drizzle emits `DESC NULLS LAST`; list queries must order the same way to use the index.
    index("content_items_project_id_state_updated_at_idx").on(
      t.projectId,
      t.state,
      t.updatedAt.desc(),
    ),
    index("content_items_series_id_target_at_idx").on(t.seriesId, t.targetAt),
    foreignKey({
      name: "content_items_current_version_fk",
      columns: [t.id, t.currentVersionId],
      foreignColumns: [contentVersions.itemId, contentVersions.id],
    }),
  ],
);

/**
 * One immutable version of an item. Versions count up from 1 per item; take the next number with
 * `nextVersionNo`, which locks the item row.
 *
 * `jobId` is the job whose result the version is. It is unique, so storing a job result twice (a
 * replayed `job.complete`) is refused instead of writing a second version. `parentVersionId` must
 * be a version of the same item. An asset a version points at cannot be deleted.
 */
export const contentVersions = pgTable(
  "content_versions",
  {
    id: uuidPrimaryKey(),
    itemId: uuid("item_id")
      .notNull()
      .references((): AnyPgColumn => contentItems.id, { onDelete: "cascade" }),
    versionNo: integer("version_no").notNull(),
    /** The state the item entered with this version. */
    stage: pipelineState("stage").notNull(),
    parentVersionId: uuid("parent_version_id"),
    /** The format version it was produced with; null for an item without a series. */
    formatVersionId: uuid("format_version_id").references(() => formatVersions.id),
    /** What kind of post the version publishes as; studio videos are `reel`s. */
    format: postFormat("format").notNull().default("reel"),
    /**
     * The photos and videos of a composed post, in order: ready `media` assets of the item,
     * checked when the version is written (`createVersion`). Empty for a studio video.
     */
    media: jsonb("media").$type<PostMediaEntry[]>().notNull().default([]),
    script: jsonb("script").$type<Script>(),
    storyboard: jsonb("storyboard").$type<Storyboard>(),
    // Typed as `AnyPgColumn` because `assets` reaches back to this table through `item_id`.
    voiceAssetId: uuid("voice_asset_id").references((): AnyPgColumn => assets.id),
    renderAssetId: uuid("render_asset_id").references((): AnyPgColumn => assets.id),
    posterAssetId: uuid("poster_asset_id").references((): AnyPgColumn => assets.id),
    /** The post caption; when null, the script's caption is used. */
    caption: text("caption"),
    notes: text("notes"),
    createdVia: versionCreatedVia("created_via").notNull(),
    createdByUser: uuid("created_by_user").references(() => users.id, { onDelete: "set null" }),
    jobId: uuid("job_id").references(() => jobs.id, { onDelete: "set null" }),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("content_versions_item_id_version_no_uq").on(t.itemId, t.versionNo),
    // Target of the composite keys that keep a version pointer within its item.
    uniqueIndex("content_versions_item_id_id_uq").on(t.itemId, t.id),
    uniqueIndex("content_versions_job_id_uq").on(t.jobId).where(sql`${t.jobId} is not null`),
    check("content_versions_version_no_ck", sql`${t.versionNo} >= 1`),
    foreignKey({
      name: "content_versions_parent_version_fk",
      columns: [t.itemId, t.parentVersionId],
      foreignColumns: [t.itemId, t.id],
    }),
  ],
);

/**
 * A decision on one version of an item. A request for changes carries a comment, and only a
 * request for changes may queue a revision (`enqueueRevision`). The checks compare the decision as
 * text, like every check on an enum in this schema.
 */
export const reviews = pgTable(
  "reviews",
  {
    id: uuidPrimaryKey(),
    itemId: uuid("item_id")
      .notNull()
      .references(() => contentItems.id, { onDelete: "cascade" }),
    versionId: uuid("version_id").notNull(),
    decision: reviewDecision("decision").notNull(),
    comment: text("comment"),
    enqueueRevision: boolean("enqueue_revision").notNull().default(false),
    userId: uuid("user_id").references(() => users.id, { onDelete: "set null" }),
    actorKind: actorKind("actor_kind").notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    index("reviews_item_id_created_at_idx").on(t.itemId, t.createdAt.desc()),
    foreignKey({
      name: "reviews_version_fk",
      columns: [t.itemId, t.versionId],
      foreignColumns: [contentVersions.itemId, contentVersions.id],
    }).onDelete("cascade"),
    check(
      "reviews_comment_ck",
      sql`${t.decision}::text <> 'request_changes' or ${t.comment} is not null`,
    ),
    check(
      "reviews_enqueue_revision_ck",
      sql`not ${t.enqueueRevision} or ${t.decision}::text = 'request_changes'`,
    ),
  ],
);

export type ContentItemRow = typeof contentItems.$inferSelect;
export type NewContentItemRow = typeof contentItems.$inferInsert;
export type ContentVersionRow = typeof contentVersions.$inferSelect;
export type NewContentVersionRow = typeof contentVersions.$inferInsert;
export type ReviewRow = typeof reviews.$inferSelect;
export type NewReviewRow = typeof reviews.$inferInsert;
