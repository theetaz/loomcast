import { SKILL_NAME_RE, type SkillFile } from "@loomcast/contracts";
import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  char,
  check,
  foreignKey,
  integer,
  jsonb,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { apiTokens } from "./auth";
import { createdAt, timestamptz, uuidPrimaryKey } from "./columns";
import { skillKind } from "./enums";
import { users } from "./users";

/**
 * A published skill or recipe that producer sessions load. Skills are global, not per workspace.
 * The files live in immutable `skill_versions`.
 *
 * A skill exists only once published, so `currentVersionId` is never null. The foreign key to
 * `skill_versions (skill_id, id)` also proves that the current version belongs to this skill. It
 * is `DEFERRABLE INITIALLY DEFERRED` (written into the migration by hand): insert the skill and
 * its first version in one transaction, with the ids generated by the caller.
 */
export const skills = pgTable(
  "skills",
  {
    id: uuidPrimaryKey(),
    name: text("name").notNull(),
    kind: skillKind("kind").notNull(),
    currentVersionId: uuid("current_version_id").notNull(),
    createdAt: createdAt(),
    updatedAt: timestamptz("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (t) => [
    uniqueIndex("skills_name_uq").on(t.name),
    check("skills_name_ck", sql`${t.name} ~ ${sql.raw(`'${SKILL_NAME_RE.source}'`)}`),
    foreignKey({
      name: "skills_current_version_fk",
      columns: [t.id, t.currentVersionId],
      foreignColumns: [skillVersions.skillId, skillVersions.id],
    }),
  ],
);

/**
 * One published version of a skill. Versions count up from 1 per skill. `checksum` is the SHA-256
 * of `skillChecksumInput(files)` and is unique per skill, so publishing files a skill already has
 * is refused; the API answers with the existing version instead.
 */
export const skillVersions = pgTable(
  "skill_versions",
  {
    id: uuidPrimaryKey(),
    skillId: uuid("skill_id")
      .notNull()
      .references((): AnyPgColumn => skills.id, { onDelete: "cascade" }),
    version: integer("version").notNull(),
    files: jsonb("files").$type<SkillFile[]>().notNull(),
    /** Lowercase hex. */
    checksum: char("checksum", { length: 64 }).notNull(),
    changelog: text("changelog"),
    publishedByUser: uuid("published_by_user").references(() => users.id, {
      onDelete: "set null",
    }),
    /** The MCP token it was published with, if any. */
    publishedByToken: uuid("published_by_token").references(() => apiTokens.id, {
      onDelete: "set null",
    }),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("skill_versions_skill_id_version_uq").on(t.skillId, t.version),
    uniqueIndex("skill_versions_skill_id_checksum_uq").on(t.skillId, t.checksum),
    // Target of `skills_current_version_fk`.
    uniqueIndex("skill_versions_skill_id_id_uq").on(t.skillId, t.id),
    check("skill_versions_version_ck", sql`${t.version} >= 1`),
    check("skill_versions_checksum_ck", sql`${t.checksum} ~ '^[0-9a-f]{64}$'`),
  ],
);

export type SkillRow = typeof skills.$inferSelect;
export type NewSkillRow = typeof skills.$inferInsert;
export type SkillVersionRow = typeof skillVersions.$inferSelect;
export type NewSkillVersionRow = typeof skillVersions.$inferInsert;
